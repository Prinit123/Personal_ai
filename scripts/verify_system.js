// scripts/verify_system.js — End-to-end verification script for Nilesh Assistant
async function verify() {
  console.log('--- 1. Testing Backend Root ---');
  try {
    const res = await fetch('http://localhost:3001/');
    const data = await res.json();
    console.log('✅ Backend root OK:', data.name, '| Status:', data.status);
  } catch (err) {
    console.error('❌ Backend root error:', err.message);
  }

  console.log('\n--- 2. Testing /api/status ---');
  try {
    const res = await fetch('http://localhost:3001/api/status');
    const data = await res.json();
    console.log('✅ Status OK: Backend:', data.backend, '| Active Provider:', data.activeProvider, '| Gemini:', data.gemini, '| Ollama:', data.ollama);
  } catch (err) {
    console.error('❌ Status error:', err.message);
  }

  console.log('\n--- 3. Testing /api/chat error handling without key ---');
  try {
    const res = await fetch('http://localhost:3001/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ message: 'Hello' }),
    });
    const data = await res.json();
    console.log('✅ /api/chat responded with status:', res.status, '| Error message received correctly:', data.error ? 'YES' : 'NO');
    console.log('   Message:', data.error);
  } catch (err) {
    console.error('❌ Chat error:', err.message);
  }

  console.log('\n--- 4. Testing Project File Generator /api/projects/apply-files ---');
  try {
    const res = await fetch('http://localhost:3001/api/projects/apply-files', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        projectName: 'test-kict-demo',
        files: [
          { path: 'README.md', content: '# KICT Computer Classes Demo\nGenerated by Nilesh.' },
          { path: 'backend/server.js', content: 'console.log("KICT Backend Ready");' }
        ]
      }),
    });
    const data = await res.json();
    console.log('✅ File application OK:', data.success, '| Files written:', data.createdFiles || data.modifiedFiles);
  } catch (err) {
    console.error('❌ Apply files error:', err.message);
  }

  console.log('\n--- 5. Testing Frontend Index HTML ---');
  try {
    const res = await fetch('http://localhost:5173/');
    const text = await res.text();
    const hasNilesh = text.includes('Nilesh');
    console.log('✅ Frontend index.html served (HTTP', res.status, '): Contains "Nilesh"?', hasNilesh ? 'YES' : 'NO');
  } catch (err) {
    console.error('❌ Frontend HTML error:', err.message);
  }

  console.log('\n--- 6. Testing Vite Transpilation of App.tsx ---');
  try {
    const res = await fetch('http://localhost:5173/src/App.tsx');
    const text = await res.text();
    const transpiledOk = res.ok && text.includes('App');
    console.log('✅ Vite transpiled App.tsx (HTTP', res.status, '): Transpilation valid?', transpiledOk ? 'YES' : 'NO');
  } catch (err) {
    console.error('❌ Vite App.tsx error:', err.message);
  }

  console.log('\n--- 7. Testing Vite Transpilation of ChatPanel.tsx ---');
  try {
    const res = await fetch('http://localhost:5173/src/components/ChatPanel.tsx');
    const text = await res.text();
    const transpiledOk = res.ok && text.includes('ChatPanel');
    console.log('✅ Vite transpiled ChatPanel.tsx (HTTP', res.status, '): Transpilation valid?', transpiledOk ? 'YES' : 'NO');
  } catch (err) {
    console.error('❌ Vite ChatPanel.tsx error:', err.message);
  }

  console.log('\n=== ALL SYSTEM TESTS COMPLETED ===');
}

verify();
